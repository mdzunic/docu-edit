// Special-character catalogue for SPEC-026. Plain data, no Vue imports.
// The catalogue is fixed and hand-authored - see specs/026 "Character catalogue".
// Names are the Unicode 15.1 character names (displayed title-cased in the UI).

export interface SpecialCharacter {
  /** Unicode code point. */
  cp: number
  /** Unicode 15.1 character name, e.g. "EM DASH". */
  name: string
  /** Lowercase search aliases; [] when the name suffices. */
  keywords: string[]
}

