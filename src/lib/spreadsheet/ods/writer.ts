/** settings.xml holding the view's ActiveTable and, when a sheet has frozen
 * panes or hides its gridlines, a `Tables` entry for each such sheet — its
 * split modes and positions as withFrozen writes them, and `ShowGrid` false
 * (SPEC-140: a generated workbook's panes and gridlines survive as .ods;
 * ods/settings.ts reads them back). A workbook with neither writes the
 * ActiveTable alone. */
export function fromScratchSettingsXml(activeTable: string, sheets: readonly Sheet[] = []): string {
  const item = (name: string, type: string, value: string | number): string => `<config:config-item config:name="${name}" config:type="${type}">${value}</config:config-item>`;
  const entries = sheets
    .filter((sheet) => sheet.frozen !== undefined || sheet.showGridLines === false)
    .map((sheet) => {
      const rows = sheet.frozen?.rows ?? 0;
      const cols = sheet.frozen?.cols ?? 0;
      const frozen =
        sheet.frozen === undefined
          ? ""
          : item("HorizontalSplitMode", "short", cols > 0 ? 2 : 0) +
            item("VerticalSplitMode", "short", rows > 0 ? 2 : 0) +
            item("HorizontalSplitPosition", "int", cols) +
            item("VerticalSplitPosition", "int", rows) +
            item("PositionRight", "int", cols) +
            item("PositionBottom", "int", rows);
      const grid = sheet.showGridLines === false ? item("ShowGrid", "boolean", "false") : "";
      return `<config:config-item-map-entry config:name="${escapeAttributeValue(sheet.name)}">${frozen}${grid}</config:config-item-map-entry>`;
    });
  const tables = entries.length === 0 ? "" : `<config:config-item-map-named config:name="Tables">${entries.join("")}</config:config-item-map-named>`;
  return (
    `${ODF_DECLARATION}<office:document-settings xmlns:office="${OFFICE_NS}" xmlns:config="${CONFIG_NS}" xmlns:ooo="${OOO_NS}" office:version="1.2">` +
    `<office:settings><config:config-item-set config:name="ooo:view-settings"><config:config-item-map-indexed config:name="Views">` +
    `<config:config-item-map-entry><config:config-item config:name="ActiveTable" config:type="string">${escapeElementText(activeTable)}</config:config-item>${tables}` +
    `</config:config-item-map-entry></config:config-item-map-indexed></config:config-item-set></office:settings></office:document-settings>`
  );
}

/** `xmlns` declarations for the optional prefixes `text` uses. */
function optionalDeclarations(text: string): string {
  return (
    (text.includes(`<number:`) ? ` xmlns:number="${NUMBER_NS}"` : "") +
    (text.includes(` calcext:`) ? ` xmlns:calcext="${CALCEXT_NS}"` : "") +
    (text.includes(`<draw:`) || text.includes(` draw:`) ? ` xmlns:draw="${DRAW_NS}"` : "") +
    (text.includes(` svg:`) || text.includes(`<svg:`) ? ` xmlns:svg="${SVG_NS}"` : "") +
    (text.includes(` xlink:`) ? ` xmlns:xlink="${XLINK_NS}"` : "")
  );
}

// --- SPEC-131: media parts -------------------------------------------------------------------

/** The model's media as a save writes it ("Media parts"): each part a
 * drawing shows, under its package path (OdsMediaPaths), and the paths of
 * those none shows. */
interface MediaPlan {
  paths: OdsMediaPaths;
  /** Path → the part, for every part a drawing shows. */
  shown: Map<string, MediaPart>;
  /** The paths of the model's parts no drawing shows. */
  unshown: Set<string>;
}

function mediaPlan(model: SpreadsheetModel): MediaPlan {
  const media = model.media ?? [];
  const paths = new OdsMediaPaths([...model.opaque.map((part) => part.name), ...media.map((part) => part.mediaId)]);
  const byId = new Map(media.map((part) => [part.mediaId, part] as const));
  const shown = new Map<string, MediaPart>();
  for (const sheet of model.sheets) {
    for (const drawing of sheet.drawings ?? []) {
      for (const id of drawingMediaIds(drawing)) {
        const part = byId.get(id);
        if (part) {
          shown.set(paths.pathOf(id, part.contentType), part);
        }
      }
    }
  }
  const unshown = new Set(media.map((part) => paths.pathOf(part.mediaId, part.contentType)).filter((path) => !shown.has(path)));
  return { paths, shown, unshown };
}

/** A media part's bytes (its deferred encode forced first). */
function mediaBytes(part: MediaPart): Uint8Array {
  ensureMediaEncoded(part);
  return base64ToBytes(part.data);
}

/** A `manifest:file-entry` for a new picture, shaped like the manifest's
 * own entries (its prefix kept). */
function manifestEntryFor(manifestXml: string, path: string, mediaType: string): string {
  const prefix = /<([\w.-]+:)?manifest\b/.exec(manifestXml)?.[1] ?? "manifest:";
  return `<${prefix}file-entry ${prefix}full-path="${escapeAttributeValue(path)}" ${prefix}media-type="${escapeAttributeValue(mediaType)}"/>`;
}

async function buildFromScratch(model: SpreadsheetModel, options: WriteOdsOptions): Promise<ZipEntryInput[]> {
  const modified = options.modified ?? clockNow();
  const locale = localeOf(options);
  const registry = new OdsStyleRegistry();
  // The generated styles.xml defines "Default" alone: every other named style is appended.
  const named = new OdsNamedStyles(model, { defines: (name) => name === "Default", appendable: true }, registry, locale);
  const conditionalFormats = new OdsConditionalFormatWriter(model, registry, { definesStyle: (name) => name === "Default", appendable: true });
  const validations = new OdsValidationWriter(model, undefined, () => false);
  const validationName = (sheet: Sheet, rule: DataValidation): string | undefined => validations.nameOf(sheet, rule);
  const plan = mediaPlan(model);
  const contentTypes = new Map((model.media ?? []).map((part) => [part.mediaId, part.contentType] as const));
  const mediaPath = (id: string): string => plan.paths.pathOf(id, contentTypes.get(id) ?? "image/png");
  // SPEC-132: every chart gets a new embedded object (ods/chartParts.ts).
  const charts = planOdsCharts(model, []);
  const chartObjectDir = (drawing: SheetDrawing): string | undefined => charts.minted.get(drawing);
  const localNames = (sheet: Sheet, trailing: string): string => odsTrailingWithNames(trailing, model, sheet, new Map());
  const scratchStyles = fromScratchOdsStylesXml(model.styles[0] ?? {}, model.theme ?? DEFAULT_THEME, locale);
  const pageSetups = new OdsPageSetupWriter("", scratchStyles, (prefix) => registry.freshName(prefix));
  // SPEC-137: one shared clock, sheets serialised sequentially (never
  // Promise.all) — each sheet's table appends to the shared `registry` in
  // sheet order, which concurrent calls would interleave incorrectly.
  const clock = createSliceClock();
  const tableTexts: string[] = [];
  for (const sheet of model.sheets) {
    tableTexts.push(
      withNewTablePageSetup(
        await serializeTableAsync(sheet, { model, registry, locale, namedStyleParent: (name) => named.parent(name), conditionalFormats, validationName, mediaPath, chartObjectDir, localNames }, clock),
        sheet,
        model,
        registry,
        pageSetups,
      ),
    );
  }
  const tables = tableTexts.join("");
  const namedExpressions = odsNamedExpressionsXml(model, odsScopeNames(model, undefined));
  const databaseRanges = odsWithTableDatabaseRanges(odsDatabaseRangesXml(model.sheets), model.sheets).text;
  const styles = registry.xml();
  const content =
    `${ODF_DECLARATION}<office:document-content xmlns:office="${OFFICE_NS}" xmlns:style="${STYLE_NS}" xmlns:text="${TEXT_NS}" ` +
    `xmlns:table="${TABLE_NS}" xmlns:fo="${FO_NS}" xmlns:of="${OF_NS}" xmlns:tableooo="${TABLEOOO_NS}"${optionalDeclarations(styles + tables)} office:version="1.2">` +
    `<office:automatic-styles>${styles}</office:automatic-styles>` +
    `<office:body><office:spreadsheet>${calculationSettings(model)}${validations.blockXml()}${tables}${namedExpressions}${databaseRanges}</office:spreadsheet></office:body></office:document-content>`;
  const active = model.sheets[model.activeSheetIndex] ?? model.sheets[0];
  // SPEC-131: every picture a drawing shows, listed in the manifest.
  const pictures: ZipEntryInput[] = [
    ...[...plan.shown].map(([path, part]) => ({ name: path, data: mediaBytes(part) })),
    ...charts.newParts.map((part) => ({ name: part.name, data: encode(part.text) })),
  ];
  const manifest = spliceManifest(FROM_SCRATCH_ODS_MANIFEST_XML, new Set(), [
    ...[...plan.shown].map(([path, part]) => manifestEntryFor(FROM_SCRATCH_ODS_MANIFEST_XML, path, part.contentType)),
    ...charts.manifestEntries,
  ]);
  return [
    { name: "mimetype", data: encode(ODS_MIMETYPE), store: true },
    { name: "META-INF/manifest.xml", data: encode(manifest) },
    ...pictures,
    { name: "meta.xml", data: encode(buildMetaXml({ title: model.title }, modified)) },
    {
      name: "styles.xml",
      data: encode(pageSetups.stylesXmlWith(withNamedStyles(scratchStyles, named.xml + conditionalFormats.stylesXml))),
    },
    { name: "content.xml", data: encode(content) },
    { name: "settings.xml", data: encode(fromScratchSettingsXml(active?.name ?? "", model.sheets)) },
  ];
}

