/** SPEC-136: a table written from the model alone (a new sheet's, a
 * from-scratch package's) with its print ranges and, when its setup is not
 * the "Default" master page's, a minted master page. */
function withNewTablePageSetup(table: string, sheet: Sheet, model: SpreadsheetModel, registry: OdsStyleRegistry, pageSetups: OdsPageSetupWriter): string {
  let text = withOdsPrintRanges(model, sheet, table);
  const minted = sheet.pageSetup === undefined ? undefined : pageSetups.masterPageFor(sheet, undefined);
  if (minted !== undefined) {
    const tabColor = tabColorHex(sheet, model);
    text = setTableAttribute(text, "table:style-name", registry.tableStyle({ masterPage: minted, display: sheet.visibility === "visible", ...(tabColor === undefined ? {} : { tabColor }) }));
  }
  return text;
}

/** A table style's master page, read from the envelope's automatic styles. */
function masterPageOf(prefix: string, styleName: string | undefined): string {
  if (styleName === undefined) {
    return "Default";
  }
  for (const match of prefix.matchAll(/<style:style\b[^>]*>/g)) {
    if (attributeValue(match[0], "style:name") === styleName && attributeValue(match[0], "style:family") === "table") {
      return attributeValue(match[0], "style:master-page-name") ?? "Default";
    }
  }
  return "Default";
}

/** The envelope prefix with generated styles added to its automatic styles
 * (the element created before `<office:body` when absent). */
function withGeneratedStyles(prefix: string, styles: string): string {
  if (styles === "") {
    return prefix;
  }
  const close = prefix.lastIndexOf("</office:automatic-styles>");
  if (close >= 0) {
    return prefix.slice(0, close) + styles + prefix.slice(close);
  }
  const selfClosing = /<office:automatic-styles\s*\/>/.exec(prefix);
  if (selfClosing) {
    return `${prefix.slice(0, selfClosing.index)}<office:automatic-styles>${styles}</office:automatic-styles>${prefix.slice(selfClosing.index + selfClosing[0].length)}`;
  }
  const body = prefix.indexOf("<office:body");
  const at = body >= 0 ? body : prefix.length;
  return `${prefix.slice(0, at)}<office:automatic-styles>${styles}</office:automatic-styles>${prefix.slice(at)}`;
}

/** A part's text (the content envelope's prefix, styles.xml) with an
 * `xmlns` declaration added to its root for every generated prefix
 * `generated` uses that the root does not declare (a producer that never
 * needed, say, `calcext`); the same text when none is missing. */
function withNamespaces(prefix: string, generated: string): string {
  const root = /<[\w.-]+:document[\w-]*\b[^>]*>/.exec(prefix);
  if (!root) {
    return prefix;
  }
  const declared = rootNamespaces(prefix);
  const missing = GENERATED_NAMESPACES.filter(([name]) => !declared.has(name) && new RegExp(`[<\\s"]${name}:`).test(generated))
    .map(([name, uri]) => ` xmlns:${name}="${uri}"`)
    .join("");
  if (missing === "") {
    return prefix;
  }
  const tag = root[0];
  const close = tag.endsWith("/>") ? tag.length - 2 : tag.length - 1;
  return prefix.slice(0, root.index) + tag.slice(0, close) + missing + tag.slice(close) + prefix.slice(root.index + tag.length);
}

/** styles.xml with SPEC-123's appended named styles (OdsNamedStyles.xml)
 * spliced in before `</office:styles>` — the element expanded when
 * self-closing, created where ODF puts it (before the automatic and master
 * styles) when absent — and a namespace they use declared on the root;
 * every other byte as it was. */
function withNamedStyles(xml: string, styles: string): string {
  if (styles === "") {
    return xml;
  }
  let next: string;
  const close = xml.lastIndexOf("</office:styles>");
  const selfClosing = /<office:styles\b[^>]*?\/>/.exec(xml);
  const emptyRoot = /<([\w.-]+:document-styles)\b([^>]*?)\/>/.exec(xml);
  if (close >= 0) {
    next = xml.slice(0, close) + styles + xml.slice(close);
  } else if (selfClosing) {
    next = `${xml.slice(0, selfClosing.index)}<office:styles>${styles}</office:styles>${xml.slice(selfClosing.index + selfClosing[0].length)}`;
  } else if (emptyRoot) {
    const root = emptyRoot[1]!;
    next = `${xml.slice(0, emptyRoot.index)}<${root}${emptyRoot[2]!}><office:styles>${styles}</office:styles></${root}>${xml.slice(emptyRoot.index + emptyRoot[0].length)}`;
  } else {
    const at = /<office:(?:automatic-styles|master-styles)\b|<\/[\w.-]+:document-styles>/.exec(xml)?.index ?? xml.length;
    next = `${xml.slice(0, at)}<office:styles>${styles}</office:styles>${xml.slice(at)}`;
  }
  return withNamespaces(next, styles);
}

async function buildSubstitution(model: SpreadsheetModel, parts: Map<string, Uint8Array>, options: WriteOdsOptions): Promise<ZipEntryInput[]> {
  const envelope = model.odsContentEnvelope;
  const contentBytes = parts.get("content.xml");
  if (!envelope || !contentBytes) {
    throw new Error("The workbook's retained package has no content envelope");
  }
  const sourceContent = decodeUtf8(contentBytes);
  const stylesXml = parts.has("styles.xml") ? decodeUtf8(parts.get("styles.xml")!) : undefined;
  const remap = sourceSheetRemap(model, parts);
  const namespaces = rootNamespaces(envelope.prefix);
  const registry = new OdsStyleRegistry([envelope.prefix, envelope.suffix, stylesXml ?? ""]);
  const book = odsStyleBookFromSource(envelope.prefix, stylesXml);
  // A rich run read from the file is written in its span's own text style.
  for (const { name, font } of book.runTextStyles()) {
    registry.adoptTextStyle(name, font, model.theme ?? DEFAULT_THEME);
  }
  const named = new OdsNamedStyles(model, { defines: (name) => book.commonCellStyle(name), appendable: stylesXml !== undefined }, registry, localeOf(options));
  const conditionalFormats = new OdsConditionalFormatWriter(model, registry, {
    definesStyle: (name) => book.commonCellStyle(name),
    appendable: stylesXml !== undefined,
  });
  // SPEC-130: a clean table is re-emitted as it is (unless its validation
  // names cannot be kept, see OdsValidationWriter).
  const validations = new OdsValidationWriter(model, envelope.prefix, (sheet) => sheet.sourceXml !== undefined && !sheet.dirty);
  const recoloured = new Set<string>();
  const plan = mediaPlan(model);
  const contentTypes = new Map((model.media ?? []).map((part) => [part.mediaId, part.contentType] as const));
  // SPEC-132: the save's chart objects — minted, regenerated, patched (ods/chartParts.ts).
  const charts = planOdsCharts(model, parts.keys());
  const context: OdsTableContext = {
    chartObjectDir: (drawing) => charts.minted.get(drawing),
    mediaPath: (id) => plan.paths.pathOf(id, contentTypes.get(id) ?? "image/png"),
    model,
    registry,
    locale: localeOf(options),
    sourceStyleNames: true,
    commonCellStyle: (name) => book.commonCellStyle(name),
    namedStyleParent: (name) => named.parent(name),
    layoutStyles: book,
    conditionalFormats,
    mappedCellStyle: (name) => book.cellStyleMaps(name) !== undefined,
    validationName: (sheet, rule) => validations.nameOf(sheet, rule),
    localNames: (sheet, trailing) => odsTrailingWithNames(trailing, model, sheet, namespaces),
  };
  let rebuilt = "";
  // SPEC-136: a table whose setup its master page no longer reads as gets minted ones (ods/pageSetup.ts).
  const pageSetups = new OdsPageSetupWriter(envelope.prefix, stylesXml, (prefix) => registry.freshName(prefix));

  // SPEC-137: a rebuilt table is serialised in SERIALISE_SLICE_MS slices —
  // one clock for the whole save, tables in order (they share the style
  // registry).
  const clock = createSliceClock();
  const envelopePrefix = envelope.prefix;
  const tables: string[] = [];
  for (const sheet of model.sheets) {
    tables.push(await tableText(sheet));
  }
  async function tableText(sheet: Sheet): Promise<string> {
    if (sheet.sourceXml === undefined) {
      const table = withNewTablePageSetup(await serializeTableAsync(sheet, context, clock), sheet, model, registry, pageSetups);
      rebuilt += table;
      return table;
    }
    const sheetRemap = copyRemap(remap, sheet);
    let text = passOdsText(sheet.sourceXml, sheetRemap, namespaces);
    if (tableNameOf(text) !== sheet.name) {
      text = setTableAttribute(text, "table:name", sheet.name);
    }
    const styleName = tableStyleNameOf(text);
    const declared = book.tableStyle(styleName);
    const hidden = sheet.visibility !== "visible";
    const color = tabColorHex(sheet, model);
    const minted = sheet.dirty || sheet.pageSetupDirty ? pageSetups.masterPageFor(sheet, styleName) : undefined;
    if (model.namesDirty) {
      text = withOdsPrintRanges(model, sheet, text);
    }
    if (declared.hidden !== hidden || declared.tabColor !== color || minted !== undefined) {
      const name = registry.tableStyle({ masterPage: minted ?? masterPageOf(envelopePrefix, styleName), display: !hidden, tabColor: color });
      text = setTableAttribute(text, "table:style-name", name);
      if (declared.tabColor !== color) {
        recoloured.add(sheet.name);
      }
    }
    if (!sheet.dirty && !validations.rebuilds(sheet) && !hasTables(sheet)) {
      // SPEC-133: a clean table still carries the model's names.
      const withNames = odsTableTextWithNames(text, model, sheet, namespaces);
      rebuilt += withNames.generated;
      return withNames.text;
    }
    const table = await serializeTableAsync(sheet, { ...context, source: text, passRetained: (retained) => passOdsText(retained, sheetRemap, namespaces) }, clock);
    rebuilt += table;
    return table;
  }
  // SPEC-128: the autofilters' database ranges regenerated; every other byte of the suffix passed.
  const databases = odsSuffixWithAutoFilters(envelope.suffix, model.sheets, {
    sourceNames: remap.orderBefore,
    retained: (retained) => passOdsText(removeRangesOnDeletedSheets(retained, remap), remap, namespaces),
    sheetPass: (sheet, retained) => passOdsText(retained, copyRemap(remap, sheet), namespaces),
  });
  // SPEC-133: the workbook's names (never passed), then the tables' database ranges.
  const names = odsSuffixWithNames(databases.suffix, model, namespaces);
  const tableRanges = odsWithTableDatabaseRanges(names.suffix, model.sheets);
  const generated = registry.xml();
  const passPrefix = (retained: string): string => passOdsText(retained, remap, namespaces);
  const prefix = withNamespaces(
    withGeneratedStyles(validations.splicePrefix(passPrefix(envelope.prefix), passPrefix), generated),
    generated + rebuilt + databases.generated + names.generated + tableRanges.generated + validations.generatedXml,
  );
  const suffix = tableRanges.text;
  const content = prefix + tables.join("") + suffix;

  // Objects and pictures only a deleted source table showed.
  const deletedNames = new Set(remap.deleted.map((name) => name.toUpperCase()));
  const deletedTexts = sourceTables(sourceContent, envelope.prefix.length, envelope.suffix.length)
    .filter((table) => deletedNames.has(table.name.toUpperCase()))
    .map((table) => sourceContent.slice(table.start, table.end));
  const shownObjects = new Set(objectsReferenced(content));
  const shownPictures = new Set([...picturesReferenced(content), ...picturesReferenced(stylesXml ?? "")]);
  // SPEC-132: an object any retained table showed that no table shows now — a deleted table's, or a
  // deleted chart's (SPEC-131's reachability rule) — leaves with its manifest entries.
  const droppedObjects = [...new Set([...deletedTexts.flatMap(objectsReferenced), ...objectsReferenced(sourceContent)])].filter((object) => !shownObjects.has(object));
  const droppedPictures = new Set(deletedTexts.flatMap(picturesReferenced).filter((picture) => !shownPictures.has(picture)));
  // SPEC-131: a picture of `media` no drawing shows any more leaves the package
  // only when no retained XML part mentions its path either.
  const otherXml = [...parts].filter(([name]) => name.endsWith(".xml") && name !== "content.xml" && name !== "styles.xml" && name !== "META-INF/manifest.xml");
  for (const path of plan.unshown) {
    if (parts.has(path) && !content.includes(path) && !(stylesXml ?? "").includes(path) && !otherXml.some(([, bytes]) => decodeUtf8(bytes).includes(path))) {
      droppedPictures.add(path);
    }
  }
  const manifestAdds = [...plan.shown].filter(([path]) => !parts.has(path));
  const dropped = (name: string): boolean => droppedPictures.has(name) || droppedObjects.some((object) => isObjectPart(name, object));

  // Each embedded object's chart ranges: a copy's own object takes its remap.
  const objectRemap = new Map<string, SheetRemap>();
  for (const sheet of model.sheets) {
    if (sheet.copiedFrom !== undefined && sheet.sourceXml !== undefined) {
      for (const object of objectsReferenced(sheet.sourceXml)) {
        const shared = model.sheets.some((other) => other !== sheet && objectsReferenced(other.sourceXml ?? "").includes(object));
        if (!shared) {
          objectRemap.set(object, copyRemap(remap, sheet));
        }
      }
    }
  }

  const active = model.sheets[model.activeSheetIndex];
  const out: ZipEntryInput[] = [];
  for (const [name, bytes] of parts) {
    if (dropped(name)) {
      continue;
    }
    let data = bytes;
    if (name === "content.xml") {
      data = encode(content);
    } else if (name === "styles.xml") {
      const withNamed = named.xml + conditionalFormats.stylesXml === "" ? stylesXml! : withNamedStyles(stylesXml!, named.xml + conditionalFormats.stylesXml);
      const next = pageSetups.stylesXmlWith(withNamed);
      if (next !== stylesXml) {
        data = encode(next);
      }
    } else if (name === "settings.xml") {
      data = encode(settingsXmlFor(decodeUtf8(bytes), model, remap, recoloured, active?.name));
    } else if (name === "META-INF/manifest.xml" && (droppedObjects.length > 0 || droppedPictures.size > 0 || manifestAdds.length > 0 || charts.manifestEntries.length > 0)) {
      const xml = decodeUtf8(bytes);
      const entries = readManifest(xml);
      const remove = new Set(
        entries.map((entry) => entry.fullPath).filter((path) => droppedPictures.has(path) || droppedObjects.some((object) => path === `${object}/` || isObjectPart(path, object))),
      );
      const listed = new Set(entries.map((entry) => entry.fullPath));
      const adds = [...manifestAdds.filter(([path]) => !listed.has(path)).map(([path, part]) => manifestEntryFor(xml, path, part.contentType)), ...charts.manifestEntries];
      const next = spliceManifest(xml, remove, adds);
      data = next === xml ? bytes : encode(next);
    } else if (plan.shown.has(name)) {
      // SPEC-131: `media` is the source of truth for its paths.
      data = mediaBytes(plan.shown.get(name)!);
    } else if (/^Object [^/]+\/content\.xml$/.test(name)) {
      const object = name.slice(0, name.indexOf("/"));
      const xml = decodeUtf8(bytes);
      const next = passOdsText(xml, objectRemap.get(object) ?? remap, rootNamespaces(xml));
      // SPEC-132: a modelled chart's regenerated or patched object is model text, never passed again.
      const own = charts.rewrite(name, next);
      data = own !== undefined ? encode(own) : next === xml ? bytes : encode(next);
    }
    out.push({ name, data });
  }
  for (const [path, part] of manifestAdds) {
    out.push({ name: path, data: mediaBytes(part) });
  }
  for (const part of charts.newParts) {
    out.push({ name: part.name, data: encode(part.text) });
  }
  return out;
}

