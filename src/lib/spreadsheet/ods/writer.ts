// The .ods writer (SPEC-121 "From scratch", "The .ods substitution path";
// SPEC-122 "The table writer"). Three paths, as xlsx/writer.ts:
//
//  1. No retained package: mimetype (first, STOREd), META-INF/manifest.xml
//     (version 1.2), meta.xml (core's buildMetaXml: the title and `modified`),
//     styles.xml (a table-cell default style holding the font, and the
//     `Default` cell style built from `model.styles[0]` — its font through a
//     font-face declaration, a colour other than automatic black, and the
//     rest of its properties as a generated cell style writes them; Calibri
//     11 pt for a new workbook — page layout `pm1`, master page `Default`;
//     and SPEC-123's named styles, as the substitution path appends them),
//     content.xml (`office:version="1.2"`; `table:calculation-settings` only
//     for the 1904 system or a custom `odsNullDate`; the generated `de-`
//     automatic styles; every sheet through serializeTable — its cells, rows,
//     columns, merges and styles, every model style a generated `de-ce`
//     one) and a settings.xml holding the view's `ActiveTable` (and, per
//     sheet with frozen panes or hidden gridlines, a `Tables` entry). The
//     `number` and `calcext` namespaces are declared only when the content
//     uses them. SPEC-128: every sheet's autofilter as a
//     `table:database-range` in a `table:database-ranges` after the tables
//     (ods/databaseRanges.ts).
//  2. Retained package, nothing changed: every part verbatim (mimetype first
//     and STOREd).
//  3. The substitution path: content.xml = the envelope prefix (the
//     generated `de-` styles appended to its automatic styles; its content
//     validations regenerated from the model, SPEC-130 — the
//     sheet-reference pass over the retained ones; a namespace the
//     rebuilt tables use declared on the root when the source did not) +
//     each sheet's table text + the suffix (the pass, and the named ranges
//     and database ranges on deleted sheets removed; SPEC-128: the database
//     ranges that are the sheets' autofilters regenerated from the model —
//     an unchanged one verbatim, a changed one patched, a new one appended,
//     a removed one dropped — per ods/databaseRanges.ts, the pass applied to
//     their retained text only). A sheet's table text:
//     its sourceXml with the pass and two start-tag splices — `table:name`
//     when it differs from the model's, `table:style-name` → a `de-ta` style
//     when the model's visibility or tab colour differs from what the source
//     table style declares — re-emitted as it is for a clean sheet and
//     rebuilt from the model by serializeTable for a dirty one (the pass
//     applied to the retained text BEFORE rebuilding, so the model's
//     formulas — which already name sheets as the model does — are never
//     passed twice; a style, row or column read from the file keeps its
//     name); a new sheet's table generated by serializeTable. settings.xml's
//     ActiveTable names the active sheet and its per-table entries follow
//     renames, deletions and duplicates (a recoloured table's TabColor item
//     is dropped — the style attribute is authoritative); SPEC-124: a dirty
//     sheet's entry takes the model's frozen panes when they differ from the
//     entry's (split modes and positions, PositionRight/PositionBottom). Embedded objects
//     and pictures only a deleted table showed are dropped with their
//     manifest entries; an object's chart ranges get the pass. styles.xml
//     is verbatim but for SPEC-123's named styles: one the workbook defines
//     that the retained styles.xml does not (a built-in applied for the
//     first time) is appended to its `office:styles` as a common table-cell
//     style (OdsNamedStyles; the element created when self-closing or
//     absent), which the generated `de-ce` styles name as their parent —
//     and SPEC-129's generated `de-cf` conditional styles after them — the
//     part re-encoded only then. Every other part is verbatim.
//
// SPEC-129: every rebuilt or new table's `calcext:conditional-formats` is
// written from the model by one OdsConditionalFormatWriter per save
// (ods/conditionalFormats.ts — the normative source); on the substitution
// path a cell style whose source automatic style carries a `style:map` is
// re-emitted in a rebuilt table as a generated `de-ce` style without it. A
// clean table keeps its source, conditional formats included.
//
// SPEC-130: the content validations are the model's (one
// OdsValidationWriter per save, ods/contentValidations.ts — the normative
// source): every rebuilt or new table's cells carry the names it assigns,
// and `table:content-validations` is regenerated — from scratch after
// `table:calculation-settings`; on the substitution path in the envelope
// prefix, where it was (or where a new one belongs), retained definitions
// and orphans through the sheet-name pass, generated ones not. A clean
// table is re-emitted verbatim and keeps the names it carries — unless they
// cannot be kept (a duplicate's rules), when it is rebuilt from the model.
//
// SPEC-131: a rebuilt or new table writes its drawings from the model
// (ods/drawingXml.ts, the normative source — an imported one's element
// patched, a created one canonical with a generated `de-gr` graphic style
// among the generated automatic styles). "Media parts": `model.media` is the
// source of truth for its paths — a picture a drawing shows is written from
// there (taking precedence over its `opaque` twin; from scratch, every one),
// a new one under `Pictures/` gets its manifest file entry (spliced), and a
// picture of `media` no drawing shows leaves the package only when no
// retained XML part mentions its path. The draw, svg and xlink namespaces
// are declared when the content uses them.
//
// A cell's informative `text:p` and a locale-dependent built-in format's
// generated number style are written in the user's locale (`locale`,
// en-US when absent). ODS has no "recalculate on load" flag: a stale cell's
// last known value is written as it is.
//
// SPEC-133 (ods/namedExpressions.ts, the normative source): the defined
// names are the model's — the workbook's `table:named-expressions` after the
// tables (from scratch) or reconciled in the suffix, each sheet's as the last
// child of its table (rebuilt, new, or clean — a clean table's text is
// otherwise verbatim); `namesDirty` alone takes the substitution path. Each
// Excel table becomes a `table:database-range` named after it, and a sheet
// holding tables is always rebuilt by serializeTable, which bakes each table
// cell's look into a generated style and writes structured references as A1
// ranges.
