/** `table:calculation-settings` for a date origin other than LibreOffice's
 * default 1899-12-30. */
function calculationSettings(model: SpreadsheetModel): string {
  const date = model.odsNullDate ?? (model.dateSystem === "1904" ? "1904-01-01" : undefined);
  return date === undefined ? "" : `<table:calculation-settings><table:null-date table:date-value="${date}"/></table:calculation-settings>`;
}

/** styles.xml from scratch (see the module header): the table-cell default
 * style holding `base`'s font family and size, and the `Default` cell style
 * built from `base` — `model.styles[0]`, so unstyled cells keep the
 * workbook's own default font in either direction. A number format of its
 * own is written as the common data style `N0`. */
export function fromScratchOdsStylesXml(base: CellStyle, theme = DEFAULT_THEME, locale = SPREADSHEET_LOCALES[DEFAULT_SPREADSHEET_LOCALE]): string {
  const family = base.font?.family === undefined ? undefined : resolveFont(base.font.family, theme);
  const properties = odsCellStyleProperties(base, theme, { face: true, omitBlack: true });
  const defaultFont = odsFontAttributes(
    base.font ? { ...(base.font.family === undefined ? {} : { family: base.font.family }), ...(base.font.sizePt === undefined ? {} : { sizePt: base.font.sizePt }) } : undefined,
    theme,
    { face: true },
  );
  const code = formatCodeOf(base, locale);
  const dataStyle = code === undefined || code.trim() === "" || /^general$/i.test(code.trim()) ? "" : odsNumberStyleXml(code, "N0");
  return (
    `${ODF_DECLARATION}<office:document-styles xmlns:office="${OFFICE_NS}" xmlns:style="${STYLE_NS}" xmlns:text="${TEXT_NS}" ` +
    `xmlns:table="${TABLE_NS}" xmlns:fo="${FO_NS}" xmlns:svg="${SVG_NS}"${dataStyle === "" ? "" : ` xmlns:number="${NUMBER_NS}"`} office:version="1.2">` +
    (family === undefined
      ? ""
      : `<office:font-face-decls><style:font-face style:name="${escapeAttributeValue(family)}" svg:font-family="${escapeAttributeValue(odsFontFamilyValue(family))}"/></office:font-face-decls>`) +
    `<office:styles>${dataStyle}<style:default-style style:family="table-cell">${defaultFont === "" ? "" : `<style:text-properties${defaultFont}/>`}</style:default-style>` +
    `<style:style style:name="Default" style:family="table-cell"${dataStyle === "" ? "" : ` style:data-style-name="N0"`}>${odsPropertyElements(properties)}</style:style></office:styles>` +
    `<office:automatic-styles><style:page-layout style:name="pm1"/></office:automatic-styles>` +
    `<office:master-styles><style:master-page style:name="Default" style:page-layout-name="pm1"/></office:master-styles></office:document-styles>`
  );
}

