import { test, expect, type Page } from "@playwright/test";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { writeFileSync } from "node:fs";
import { randomUUID } from "node:crypto";
import { DocumentBuilder } from "../src/lib/generate/builder";

// SPEC-045 — the document generation API. The API itself (fluent builder,
// JSON description, validation, round-trip fidelity, performance) is
// exercised by src/lib/generate/*.spec.ts, which can run headlessly and
// assert on the canonical model directly. What only a real browser can
// confirm is the other end of the promise those unit tests make: a file
// this API writes (AC-2) is one this product's own editor can actually
// open and render (AC-12), the same way a user opening any other document
// would (AC-16's "no download round trip" claim is unit-tested in
// openInEditor.spec.ts against jsdom's Blob/File — this file starts from a
// real on-disk file through the real file-picker input instead, so the two
// together cover both the in-memory and the picked-file path).

function writeTempFile(bytes: Uint8Array, name: string): string {
  const path = join(tmpdir(), `${randomUUID()}-${name}`);
  writeFileSync(path, bytes);
  return path;
}

async function openFile(page: Page, path: string): Promise<void> {
  const consoleErrors: string[] = [];
  page.on("console", (msg) => {
    if (msg.type() === "error") consoleErrors.push(msg.text());
  });
  await page.goto("/");
  await page.getByTestId("open-document-input").setInputFiles(path);
  await expect(page).toHaveURL(/\/doc\/.+/);
  expect(consoleErrors).toEqual([]);
}

// 1x1 red PNG, matches the fixture used by src/lib/generate/roundTrip.spec.ts.
const PNG_BASE64 = "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNk+A8AAQUBAScY42YAAAAASUVORK5CYII=";

function buildFixtureDoc(): DocumentBuilder {
  return new DocumentBuilder({ title: "Generated Fixture" })
    .addHeading("Generated Fixture", 1)
    .addParagraph([{ text: "Bold lead-in. ", bold: true }, "Plain continuation."])
    .addList(["First item", "Second item"], { style: "bullet" })
    .addTable({ header: true, rows: [["Col A", "Col B"], ["1", "2"]] })
    .addImage({ data: PNG_BASE64, contentType: "image/png", altText: "A red dot" })
    .setHeader("Fixture header")
    .setFooter("Fixture footer");
}

for (const format of ["docx", "odt"] as const) {
  test(`a ${format} generated by DocumentBuilder opens with heading, formatted text, list, table and image intact (AC-1, AC-2, AC-12, AC-13)`, async ({
    page,
  }) => {
    const bytes = await buildFixtureDoc().toBytes(format);
    const path = writeTempFile(bytes, `fixture.${format}`);

    await openFile(page, path);

    const content = page.getByTestId("document-content");
    await expect(content.getByRole("heading", { name: "Generated Fixture" })).toBeVisible();
    await expect(content.getByText("Bold lead-in.")).toBeVisible();
    await expect(content.getByText("Plain continuation.")).toBeVisible();
    await expect(content.getByText("First item")).toBeVisible();
    await expect(content.getByText("Second item")).toBeVisible();
    await expect(content.getByText("Col A")).toBeVisible();
    await expect(content.getByText("Col B")).toBeVisible();
    await expect(content.locator('[data-testid="doc-image"]')).toBeVisible();
    await expect(page.getByText("Fixture header")).toBeVisible();
    await expect(page.getByText("Fixture footer")).toBeVisible();

    await page.screenshot({ path: `test-results/SPEC-045-${format}-fixture.png`, fullPage: true });
  });
}

test("a JSON document description (AC-4) produces the same content in the editor as the equivalent builder calls", async ({
  page,
}) => {
  const fromDescription = DocumentBuilder.fromDescription({
    title: "From Description",
    body: [
      { type: "heading", text: "From Description", level: 1 },
      { type: "paragraph", text: "Built from data, not imperative code." },
    ],
  });
  const bytes = await fromDescription.toBytes("docx");
  const path = writeTempFile(bytes, "description.docx");

  await openFile(page, path);

  const content = page.getByTestId("document-content");
  await expect(content.getByRole("heading", { name: "From Description" })).toBeVisible();
  await expect(content.getByText("Built from data, not imperative code.")).toBeVisible();
});

test("a multi-section report with page breaks and a table of contents opens with a populated outline and correct page count (AC-1)", async ({
  page,
}) => {
  const builder = new DocumentBuilder({ title: "Report" })
    .addHeading("Report", 1)
    .addTableOfContents()
    .addPageBreak()
    .addHeading("Chapter One", 1)
    .addParagraph("Chapter one body.")
    .addPageBreak()
    .addHeading("Chapter Two", 1)
    .addParagraph("Chapter two body.");
  const bytes = await builder.toBytes("docx");
  const path = writeTempFile(bytes, "report.docx");

  await openFile(page, path);

  await expect(page.getByTestId("outline-pane").getByText("Chapter One")).toBeVisible();
  await expect(page.getByTestId("outline-pane").getByText("Chapter Two")).toBeVisible();
  const content = page.getByTestId("document-content");
  await expect(content.getByRole("heading", { name: "Chapter One" })).toBeVisible();
  await expect(content.getByRole("heading", { name: "Chapter Two" })).toBeVisible();
  await expect(page.getByText("Page 1 of 3")).toBeVisible();
});

test("an empty document (zero body blocks) is accepted and opens as a blank, valid document (AC-10, AC-11)", async ({
  page,
}) => {
  const bytes = await new DocumentBuilder({ title: "Empty" }).toBytes("docx");
  const path = writeTempFile(bytes, "empty.docx");

  await openFile(page, path);

  await expect(page.getByTestId("document-content")).toBeVisible();
  await expect(page.getByText("Page 1 of 1")).toBeVisible();
});
