import { test, expect } from "@playwright/test";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { unzip } from "../src/lib/core/zip";
import { PresentationBuilder } from "../src/lib/generate/presentation";
import { readOdp, readPptx } from "../src/lib/generate/readDeck";
import { slideOutline } from "../src/lib/presentation/slideModel";

// SPEC-106 — the presentation generation API. The API itself (builder,
// deck description, slide Markdown, HTML export, round trips, performance)
// is exercised headlessly by src/lib/generate/deck*.spec.ts,
// presentation.spec.ts and slideMarkdown.spec.ts. This file proves the two
// ends a unit test cannot: on the Node side, that the bytes really are a
// package the product's own readers reopen; in the browser, the hand-off — a
// deck built in the page through PresentationBuilder, stored with
// storePresentation (storeDocument is typed for the text model and will not
// take a deck), opens at /slides/:id with its title on the stage, three
// thumbnails in the filmstrip, its note in the notes panel, and a download
// that reopens with the same three slides.

// 4×2 PNG.
const PNG = "iVBORw0KGgoAAAANSUhEUgAAAAQAAAACCAAAAABawyK/AAAAC0lEQVR4nGNggAEAAAoAAX+AdF4AAAAASUVORK5CYII=";

function threeSlides(): PresentationBuilder {
  return new PresentationBuilder({ title: "Generated deck" })
    .addTitleSlide("Quarterly review", "Prepared 30 September")
    .setNotes(["Lead with Europe."])
    .addBulletSlide("Highlights", ["Revenue up 12%", ["Europe up 20%", "APAC flat"]])
    .addImageSlide("Pipeline", { data: PNG, contentType: "image/png" });
}

test("Node side: the generated bytes are a .pptx and an .odp the product's readers reopen (AC-9, AC-19)", async () => {
  const builder = threeSlides();
  const pptx = await builder.toBytes("pptx");
  const odp = await builder.toBytes("odp");

  const pptxParts = await unzip(pptx);
  expect(pptxParts.has("ppt/presentation.xml")).toBe(true);
  expect(pptxParts.has("ppt/slides/slide3.xml")).toBe(true);
  expect(pptxParts.has("ppt/notesSlides/notesSlide1.xml")).toBe(true);
  expect(pptxParts.has("ppt/media/image1.png")).toBe(true);
  const odpParts = await unzip(odp);
  expect(new TextDecoder().decode(odpParts.get("mimetype"))).toBe("application/vnd.oasis.opendocument.presentation");

  for (const deck of [await readPptx(pptx, "Generated deck"), await readOdp(odp, "Generated deck")]) {
    expect(deck.slides.map((slide) => slideOutline(slide).title)).toEqual(["Quarterly review", "Highlights", "Pipeline"]);
    expect(slideOutline(deck.slides[1]).lines).toEqual(["Revenue up 12%", "Europe up 20%", "APAC flat"]);
    expect(deck.slides[0].notes).toEqual(["Lead with Europe."]);
    expect(deck.slides[2].frames.some((frame) => frame.kind === "image")).toBe(true);
  }
  expect(builder.fileName()).toBe("Generated deck.pptx");
});

test("browser: a deck built through PresentationBuilder and stored with storePresentation opens at /slides/:id, and its download reopens (AC-26)", async ({
  page,
}) => {
  const consoleErrors: string[] = [];
  page.on("console", (msg) => {
    if (msg.type() === "error") consoleErrors.push(msg.text());
  });
  await page.goto("/");
  await expect(page.getByTestId("new-presentation")).toBeVisible();

  // Build and store in the page itself, through the app's own modules (Vite
  // serves them by path). touchDocument writes the record through to storage
  // at once, so the navigation below finds it after the reload.
  const generateModule = "/src/lib/generate/presentation.ts";
  const storeModule = "/src/lib/documentStore.ts";
  const id: string = await page.evaluate(
    async ({ generateModule, storeModule, png }) => {
      const { PresentationBuilder } = await import(/* @vite-ignore */ generateModule);
      const { storePresentation, touchDocument } = await import(/* @vite-ignore */ storeModule);
      const deck = new PresentationBuilder({ title: "Generated in the browser" })
        .addTitleSlide("Quarterly review", "Prepared 30 September")
        .setNotes(["Lead with Europe."])
        .addBulletSlide("Highlights", ["Revenue up 12%", ["Europe up 20%", "APAC flat"]])
        .addImageSlide("Pipeline", { data: png, contentType: "image/png" })
        .toDeck();
      storePresentation(deck);
      await touchDocument(deck.id);
      return deck.id;
    },
    { generateModule, storeModule, png: PNG },
  );

  // The kind guard reads documentKindOf(id) off the stored record: the deck
  // id under the text editor's route is handed to /slides/:id.
  await page.goto(`/doc/${id}`);
  await expect(page).toHaveURL(new RegExp(`/slides/${id}$`));
  await expect(page.getByTestId("presentation-view")).toBeVisible();
  expect(await page.evaluate(async ({ storeModule, id }) => (await import(/* @vite-ignore */ storeModule)).documentKindOf(id), { storeModule, id })).toBe(
    "presentation",
  );

  // The stage shows the title; the filmstrip shows three thumbnails.
  await expect(page.getByTestId("stage-workspace").getByText("Quarterly review")).toBeVisible();
  await expect(page.getByTestId("filmstrip-slide")).toHaveCount(3);

  // The notes panel shows the generated note.
  if ((await page.getByTestId("slides-notes-panel").count()) === 0) {
    await page.getByTestId("slides-notes-toggle").click();
  }
  await expect(page.getByTestId("slides-notes-editor")).toHaveValue("Lead with Europe.");
  await page.screenshot({ path: "test-results/SPEC-106-generated-deck.png", fullPage: true });

  // A download reopens with the same three slides.
  const downloadPromise = page.waitForEvent("download");
  await page.getByTestId("presentation-download").click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toBe("Generated in the browser.pptx");
  const filePath = join(tmpdir(), `spec106-${id}.pptx`);
  await download.saveAs(filePath);

  await page.goto("/");
  await page.getByTestId("open-document-input").setInputFiles(filePath);
  await expect(page).toHaveURL(/\/slides\/.+/);
  await expect(page.getByTestId("presentation-view")).toBeVisible();
  await expect(page.getByTestId("filmstrip-slide")).toHaveCount(3);
  await expect(page.getByTestId("stage-workspace").getByText("Quarterly review")).toBeVisible();
  await page.getByTestId("filmstrip-slide").nth(1).click();
  await expect(page.getByTestId("stage-workspace").getByText("Highlights")).toBeVisible();
  await expect(page.getByTestId("stage-workspace").getByText("Europe up 20%")).toBeVisible();
  await page.getByTestId("filmstrip-slide").nth(0).click();
  await expect(page.getByTestId("slides-notes-editor")).toHaveValue("Lead with Europe.");
  expect(consoleErrors).toEqual([]);
});
