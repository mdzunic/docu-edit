import { test, expect, type Locator, type Page } from "@playwright/test";
import { randomUUID } from "node:crypto";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { getCell } from "../src/lib/spreadsheet/address";
import { readWorkbook } from "../src/lib/generate/readWorkbook";
import { WorkbookBuilder } from "../src/lib/generate/workbook";

// SPEC-140 — the workbook generation API. The API itself (builder, JSON
// description, validation paths, the round-trip relation, performance) is
// exercised headlessly by src/lib/generate/workbook*.spec.ts. This file
// proves what only a real browser can: a workbook WorkbookBuilder writes in
// Node — the Reference's "Q3 sales" plus a second sheet "Notes" — opens in
// the product's own editor through the library's file picker, as .xlsx and
// as .ods, showing the formula's computed and formatted value (the cached
// value the builder wrote, never "0" or blank), the formula itself in the
// formula bar, both sheet tabs and the frozen header row; and the editor's
// own download of it re-reads with readWorkbook to the same total.

/** The Reference's "Q3 sales" workbook plus a "Notes" sheet. */
function q3Sales(): WorkbookBuilder {
  return new WorkbookBuilder({ title: "Q3 sales" })
    .defineStyle("header", { font: { bold: true }, fill: "#dce6f1", borders: { bottom: "thin" } })
    .addSheet("Sales")
    .setRow("A1", ["Region", "July", "August", "September", "Total"])
    .setRows("A2", [
      ["East", 1200, 1350, 1410],
      ["West", 980, 1010, 1130],
    ])
    .setFormula("E2", "SUM(B2:D2)")
    .setFormula("E3", "SUM(B3:D3)")
    .style("A1:E1", "header")
    .numberFormat("B2:E3", "$#,##0.00")
    .columnWidth("A", { chars: 14 })
    .freeze({ rows: 1 })
    .addSheet("Notes")
    .setCell("A1", "Generated by WorkbookBuilder");
}

function cell(page: Page, ref: string): Locator {
  return page.locator(`[data-testid="sheet-cell"][data-ref="${ref}"]`);
}

function rowHeader(page: Page, row: number): Locator {
  return page.getByTestId("sheet-row-header").filter({ hasText: new RegExp(`^${row}$`) });
}

async function openFile(page: Page, path: string): Promise<void> {
  await page.goto("/");
  await page.getByTestId("open-document-input").setInputFiles(path);
  await expect(page).toHaveURL(/\/sheets\/.+/);
}

for (const format of ["xlsx", "ods"] as const) {
  test(`a .${format} WorkbookBuilder wrote in Node opens at /sheets/:id with its computed total, formula, tabs and frozen row, and its download re-reads (AC-51, AC-52, AC-53)`, async ({
    page,
  }) => {
    const consoleErrors: string[] = [];
    page.on("console", (msg) => {
      if (msg.type() === "error") consoleErrors.push(msg.text());
    });
    const builder = q3Sales();
    // A directory of its own, so the file — and so the opened workbook's
    // title — is exactly "Q3 sales".
    const path = join(mkdtempSync(join(tmpdir(), "spec140-")), builder.fileName(format));
    writeFileSync(path, await builder.toBytes(format));

    await openFile(page, path);

    await expect(cell(page, "A1")).toHaveText("Region");
    // The SUM's cached value, computed by the builder and formatted.
    await expect(cell(page, "E2")).toHaveText("$3,960.00");
    await expect(cell(page, "E3")).toHaveText("$3,120.00");

    await cell(page, "E2").click();
    await expect(page.getByTestId("name-box")).toHaveValue("E2");
    await expect(page.getByTestId("spreadsheet-grid")).toHaveAttribute("aria-activedescendant", "sheet-cell-E2");
    await expect(page.getByTestId("formula-bar-content")).toHaveText("=SUM(B2:D2)");

    await expect(page.getByTestId("sheet-tab")).toHaveText(["Sales", "Notes"]);
    await expect(page.getByTestId("sheet-tab").filter({ hasText: /^\s*Notes\s*$/ })).toHaveCount(1);

    // Frozen: row 1 stays on screen, under the column letters, after the
    // grid scrolls 200 default-height (20 px) rows down.
    const grid = page.getByTestId("spreadsheet-grid");
    const gridBox = (await grid.boundingBox())!;
    await grid.evaluate((element) => {
      element.scrollTop += 200 * 20;
      element.dispatchEvent(new Event("scroll"));
    });
    await expect(rowHeader(page, 210)).toBeVisible();
    await expect(rowHeader(page, 1)).toBeVisible();
    await expect(cell(page, "A1")).toBeVisible();
    await expect(cell(page, "A1")).toHaveText("Region");
    await expect(rowHeader(page, 2)).toBeHidden();
    const header = (await rowHeader(page, 1).boundingBox())!;
    expect(header.y).toBeGreaterThanOrEqual(gridBox.y);
    expect(header.y).toBeLessThan(gridBox.y + 60);

    // The editor's own download re-reads with readWorkbook: E2 is 3960.
    const downloadPromise = page.waitForEvent("download");
    await page.getByTestId("spreadsheet-download").click();
    const download = await downloadPromise;
    expect(download.suggestedFilename()).toBe(`Q3 sales.${format}`);
    const savedPath = join(tmpdir(), `${randomUUID()}-${download.suggestedFilename()}`);
    await download.saveAs(savedPath);
    const model = await readWorkbook(readFileSync(savedPath));
    expect(model.format).toBe(format);
    expect(model.sheets.map((sheet) => sheet.name)).toEqual(["Sales", "Notes"]);
    const e2 = getCell(model.sheets[0]!, 1, 4);
    expect(e2?.value).toBe(3960);
    expect(e2?.formula).toBe("SUM(B2:D2)");

    expect(consoleErrors).toEqual([]);
  });
}
